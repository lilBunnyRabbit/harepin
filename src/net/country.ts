const COUNTRY_OF_ZONE = new Map(Object.entries(ZONES).flatMap(([code, zones]) => zones.split(" ").map((zone) => [zone, code] as const)));
const REGIONAL_A = 0x1f1e6;
const NAMES = new Intl.DisplayNames(["en"], { type: "region", fallback: "none" });

export function country_of_zone(zone: string): string | null {
  return COUNTRY_OF_ZONE.get(zone) ?? null;
}

export function own_country(): string | null {
  return country_of_zone(Intl.DateTimeFormat().resolvedOptions().timeZone);
}

export function clean_country(raw: unknown): string | null {
  return typeof raw === "string" && Object.hasOwn(ZONES, raw) ? raw : null;
}

export function country_name(code: string): string {
  return NAMES.of(code) ?? code;
}

export function flag(code: string): string {
  return String.fromCodePoint(...[...code].map((letter) => REGIONAL_A + letter.charCodeAt(0) - 65));
}
