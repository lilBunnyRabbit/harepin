import { writeFileSync } from "node:fs";
import { measure, tabled_specs } from "../src/ai/capability";
import { spec_hash } from "../src/car/cars";

// bun scripts/ai-capability.ts: measures every stock car and preset build and writes src/ai/capability-table.ts, so a
// field of them plans without measuring at its start. `capability.test.ts` fails while the table is stale.
const rows = tabled_specs().map(({ name, spec }) => {
  const fields = Object.entries(measure(spec)).map(([k, v]) => `${k}: ${v}`);
  return `  // ${name}\n  "${spec_hash(spec)}": { ${fields.join(", ")} },`;
});
const out = `// Generated by scripts/ai-capability.ts: never edit by hand.\nimport type { Capability } from "./capability";\n\nexport const MEASURED: Readonly<Record<string, Capability>> = {\n${rows.join("\n")}\n};\n`;
writeFileSync(new URL("../src/ai/capability-table.ts", import.meta.url), out);
console.log(`${rows.length} builds measured`);
